export type IncomingRace = Record<string, unknown>;

export type UpsertRaceRegistryResult =
  | {
      ok: true;
      race: {
        id: string;
        name: string;
        slug: string | null;
        raceDate: Date;
        companyRaceId: string | null;
      };
      registryMirror: ReturnType<typeof serializeRegistryMirror>;
    }
  | { ok: false; status: number; error: string };

function slugifyTag(raw: string): string {
  return raw
    .trim()
    .toLowerCase()
    .replace(/\s+/g, "-")
    .replace(/[^a-z0-9-]/g, "");
}

/** Tags from optional `tags` array and/or comma/semicolon `keywords` string. */
function tagsFromPayload(racePayload: IncomingRace): string[] {
  const out: string[] = [];
  const tagsRaw = racePayload.tags;
  if (Array.isArray(tagsRaw)) {
    for (const t of tagsRaw) {
      const s = slugifyTag(String(t));
      if (s) out.push(s);
    }
  }
  const keywordsRaw = racePayload.keywords;
  if (typeof keywordsRaw === "string" && keywordsRaw.trim()) {
    for (const part of keywordsRaw.split(/[,;]/)) {
      const s = slugifyTag(part);
      if (s) out.push(s);
    }
  }
  return [...new Set(out)];
}

function courseSegmentsArrayFromPayload(
  racePayload: IncomingRace
): unknown[] | null {
  if (!("courseSegments" in racePayload)) return null;
  let segments: unknown = racePayload.courseSegments;
  if (typeof segments === "string" && segments.trim()) {
    try {
      segments = JSON.parse(segments);
    } catch {
      return [];
    }
  }
  if (!Array.isArray(segments)) return [];
  return segments;
}

function countWritableSegmentsInPayload(racePayload: IncomingRace): number {
  const segments = courseSegmentsArrayFromPayload(racePayload);
  if (segments === null) return 0;
  let n = 0;
  for (const item of segments) {
    if (!item || typeof item !== "object") continue;
    const o = item as Record<string, unknown>;
    const sourceSegmentId =
      typeof o.sourceSegmentId === "string" && o.sourceSegmentId.trim()
        ? o.sourceSegmentId.trim()
        : typeof o.companySegmentId === "string" && o.companySegmentId.trim()
          ? o.companySegmentId.trim()
          : typeof o.id === "string" && o.id.trim()
            ? o.id.trim()
            : "";
    const name =
      typeof o.name === "string" ? o.name.trim() : String(o.name ?? "").trim();
    if (sourceSegmentId && name) n++;
  }
  return n;
}

/** Upsert segments from Race Manage push; omit key to leave existing rows unchanged. */
async function syncRegistryCourseSegments(
  raceRegistryId: string,
  racePayload: IncomingRace
): Promise<number> {
  const segments = courseSegmentsArrayFromPayload(racePayload);
  if (segments === null) return -1;

  const incomingIds: string[] = [];
  for (const item of segments) {
    if (!item || typeof item !== "object") continue;
    const o = item as Record<string, unknown>;
    const sourceSegmentId =
      typeof o.sourceSegmentId === "string" && o.sourceSegmentId.trim()
        ? o.sourceSegmentId.trim()
        : typeof o.companySegmentId === "string" && o.companySegmentId.trim()
          ? o.companySegmentId.trim()
          : typeof o.id === "string" && o.id.trim()
            ? o.id.trim()
            : "";
    if (!sourceSegmentId) continue;
    const orderRaw = o.order;
    const order =
      typeof orderRaw === "number" && Number.isFinite(orderRaw)
        ? orderRaw
        : parseInt(String(orderRaw ?? 0), 10) || 0;
    const name =
      typeof o.name === "string" ? o.name.trim() : String(o.name ?? "").trim();
    if (!name) continue;
    incomingIds.push(sourceSegmentId);
    const mileMarker =
      typeof o.mileMarker === "string" ? o.mileMarker.trim() || null : null;
    const description =
      typeof o.description === "string" ? o.description.trim() || null : null;
    const runTip =
      typeof o.runTip === "string" ? o.runTip.trim() || null : null;
    const guideLandmarks =
      typeof o.guideLandmarks === "string" ? o.guideLandmarks.trim() || null : null;
    const guideWater =
      typeof o.guideWater === "string" ? o.guideWater.trim() || null : null;
    const guideElevation =
      typeof o.guideElevation === "string" ? o.guideElevation.trim() || null : null;

    await prisma.race_registry_course_segments.upsert({
      where: { sourceSegmentId },
      create: {
        raceRegistryId,
        sourceSegmentId,
        order,
        name,
        mileMarker,
        description,
        runTip,
        guideLandmarks,
        guideWater,
        guideElevation,
      },
      update: {
        raceRegistryId,
        order,
        name,
        mileMarker,
        description,
        runTip,
        guideLandmarks,
        guideWater,
        guideElevation,
      },
    });
  }

  if (incomingIds.length === 0) {
    return 0;
  }
  await prisma.race_registry_course_segments.deleteMany({
    where: {
      raceRegistryId,
      sourceSegmentId: { notIn: incomingIds },
    },
  });
  return incomingIds.length;
}

function logoUrlFromPayload(racePayload: IncomingRace): string | null {
  for (const key of ["raceLogo", "raceDisplayPhoto", "ogImage"] as const) {
    const v = racePayload[key];
    if (typeof v === "string" && v.trim()) return v.trim();
  }
  return null;
}

/** When key absent, return undefined (do not update). When present, allow null to clear. */
function readOptionalTrimmedString(
  payload: IncomingRace,
  key: string
): string | null | undefined {
  if (!(key in payload)) return undefined;
  const v = payload[key];
  if (v === null) return null;
  if (typeof v === "string") return v.trim() || null;
  return null;
}

function readOptionalDateTime(
  payload: IncomingRace,
  key: string
): Date | null | undefined {
  if (!(key in payload)) return undefined;
  const v = payload[key];
  if (v === null) return null;
  if (typeof v === "string" && v.trim()) {
    const d = new Date(v.trim());
    return Number.isNaN(d.getTime()) ? null : d;
  }
  return null;
}

/** When key absent, return undefined (do not update). */
function readOptionalBoolean(
  payload: IncomingRace,
  key: string
): boolean | undefined {
  if (!(key in payload)) return undefined;
  const v = payload[key];
  if (typeof v === "boolean") return v;
  return undefined;
}

/**
 * Upserts race_registry from Race Manage / Company prodpush payload.
 * Lookup order: registryId → companyRegistrationId → slug → companyRaceId+slug.
 */
export async function upsertRaceRegistryFromPayload(
  racePayload: IncomingRace
): Promise<UpsertRaceRegistryResult> {
  try {
    if (!racePayload || typeof racePayload !== "object") {
      return { ok: false, status: 400, error: "race payload is required" };
    }

    const companyRaceId =
      racePayload.companyRaceId != null &&
      String(racePayload.companyRaceId).trim()
        ? String(racePayload.companyRaceId).trim()
        : racePayload.id != null && String(racePayload.id).trim()
          ? String(racePayload.id).trim()
          : "";

    if (!companyRaceId) {
      return {
        ok: false,
        status: 400,
        error: "companyRaceId or race.id is required",
      };
    }

    const registryIdRaw = racePayload.registryId ?? racePayload.prodRaceId;
    const registryId =
      registryIdRaw != null && String(registryIdRaw).trim()
        ? String(registryIdRaw).trim()
        : null;

    const companyRegistrationId =
      racePayload.companyRegistrationId != null &&
      String(racePayload.companyRegistrationId).trim()
        ? String(racePayload.companyRegistrationId).trim()
        : null;

    const parentRaceIdRaw = readOptionalTrimmedString(racePayload, "parentRaceId");
    const parentRaceId =
      parentRaceIdRaw === undefined ? undefined : parentRaceIdRaw;

    const raceDateRaw = racePayload.raceDate;
    if (raceDateRaw == null || raceDateRaw === "") {
      return {
        ok: false,
        status: 400,
        error: "raceDate required before pushing to prod",
      };
    }

    const raceDate = new Date(String(raceDateRaw));
    if (Number.isNaN(raceDate.getTime())) {
      return { ok: false, status: 400, error: "Invalid raceDate" };
    }

    const nameVal =
      racePayload.name != null ? String(racePayload.name).trim() : "Unnamed race";
    const slugVal =
      racePayload.slug != null && String(racePayload.slug).trim()
        ? String(racePayload.slug).trim()
        : null;

    const isVirtual = Boolean(racePayload.isVirtual);

    const locationCity =
      racePayload.locationCity != null
        ? String(racePayload.locationCity).trim() || null
        : null;
    const state =
      racePayload.state != null
        ? String(racePayload.state).trim() || null
        : null;
    const description =
      racePayload.description != null
        ? String(racePayload.description).trim() || null
        : null;
    const registrationUrl =
      racePayload.registrationUrl != null
        ? String(racePayload.registrationUrl).trim() || null
        : null;

    /** Slim sync: course, charity, venue, keywords, external URLs stay on company only. */
    const tagList = tagsFromPayload(racePayload);
    const logoUrl = logoUrlFromPayload(racePayload);
    const startTimeStr = readOptionalTrimmedString(racePayload, "startTime");

    let distanceLabel: string | null | undefined = undefined;
    if ("distanceLabel" in racePayload) {
      const raw = racePayload.distanceLabel;
      if (raw === null) distanceLabel = null;
      else if (typeof raw === "string") distanceLabel = raw.trim() || null;
      else distanceLabel = null;
    } else if ("distanceLabelSnap" in racePayload) {
      const raw = racePayload.distanceLabelSnap;
      if (raw === null) distanceLabel = null;
      else if (typeof raw === "string") distanceLabel = raw.trim() || null;
      else distanceLabel = null;
    }

    let distanceMeters: number | null | undefined = undefined;
    if ("distanceMeters" in racePayload) {
      const raw = racePayload.distanceMeters;
      if (raw === null) distanceMeters = null;
      else if (typeof raw === "number" && Number.isFinite(raw))
        distanceMeters = Math.round(raw);
      else if (typeof raw === "string" && raw.trim()) {
        const n = parseInt(raw.trim(), 10);
        distanceMeters = Number.isFinite(n) ? n : null;
      } else distanceMeters = null;
    }

    const packetPickupLocation = readOptionalTrimmedString(
      racePayload,
      "packetPickupLocation"
    );
    const packetPickupTime = readOptionalTrimmedString(
      racePayload,
      "packetPickupTime"
    );
    const packetPickupDescription = readOptionalTrimmedString(
      racePayload,
      "packetPickupDescription"
    );
    const spectatorInfo = readOptionalTrimmedString(racePayload, "spectatorInfo");
    const logisticsInfo = readOptionalTrimmedString(racePayload, "logisticsInfo");
    const gearDropInstructions = readOptionalTrimmedString(
      racePayload,
      "gearDropInstructions"
    );
    const courseMapUrlFromPayload = readOptionalTrimmedString(
      racePayload,
      "courseMapUrl"
    );
    const courseSlugFromPayload = readOptionalTrimmedString(
      racePayload,
      "courseSlug"
    );
    const startLineLabel = readOptionalTrimmedString(
      racePayload,
      "startLineLabel"
    );
    const finishLineLabel = readOptionalTrimmedString(
      racePayload,
      "finishLineLabel"
    );
    const isLoop = readOptionalBoolean(racePayload, "isLoop");
    const resultsUrlFromPayload = readOptionalTrimmedString(
      racePayload,
      "resultsUrl"
    );
    const packetPickupDate = readOptionalDateTime(
      racePayload,
      "packetPickupDate"
    );

    const summaryPhrase = readOptionalTrimmedString(racePayload, "summaryPhrase");
    let charityNameResolved: string | null | undefined = undefined;
    if ("charityName" in racePayload) {
      charityNameResolved =
        readOptionalTrimmedString(racePayload, "charityName") ?? null;
    } else if ("charitySupports" in racePayload) {
      charityNameResolved =
        readOptionalTrimmedString(racePayload, "charitySupports") ?? null;
    }
    const charityUrlExtra = readOptionalTrimmedString(racePayload, "charityUrl");
    const officialWebsiteUrl = readOptionalTrimmedString(racePayload, "raceUrl");
    const registrationOpenDate = readOptionalDateTime(
      racePayload,
      "registrationOpenDate"
    );
    const registrationOpenNow = readOptionalBoolean(
      racePayload,
      "registrationOpenNow"
    );
    const registrationCloseDate = readOptionalDateTime(
      racePayload,
      "registrationDeadline"
    );
    const registrationSoldOut = readOptionalBoolean(
      racePayload,
      "registrationSoldOut"
    );
    const transferDeadline = readOptionalDateTime(
      racePayload,
      "transferDeadline"
    );

    let registrationFee: number | null | undefined = undefined;
    if ("priceCents" in racePayload) {
      const raw = racePayload.priceCents;
      if (raw === null) registrationFee = null;
      else if (typeof raw === "number" && Number.isFinite(raw)) {
        registrationFee = Math.round(raw) / 100;
      } else if (typeof raw === "string" && raw.trim()) {
        const n = parseInt(raw.trim(), 10);
        registrationFee = Number.isFinite(n) ? n / 100 : null;
      } else registrationFee = null;
    }

    const updateData = {
      name: nameVal,
      slug: slugVal,
      raceDate,
      isVirtual,
      isActive: true,
      city: locationCity,
      state,
      description,
      registrationUrl,
      companyRaceId,
      ...(tagList.length > 0 ? { tags: tagList } : {}),
      logoUrl,
      ...(startTimeStr !== undefined ? { startTime: startTimeStr } : {}),
      ...(distanceLabel !== undefined ? { distanceLabel } : {}),
      ...(distanceMeters !== undefined ? { distanceMeters } : {}),
      ...(packetPickupLocation !== undefined
        ? { packetPickupLocation }
        : {}),
      ...(packetPickupDate !== undefined ? { packetPickupDate } : {}),
      ...(packetPickupTime !== undefined ? { packetPickupTime } : {}),
      ...(packetPickupDescription !== undefined
        ? { packetPickupDescription }
        : {}),
      ...(spectatorInfo !== undefined ? { spectatorInfo } : {}),
      ...(logisticsInfo !== undefined ? { logisticsInfo } : {}),
      ...(gearDropInstructions !== undefined
        ? { gearDropInstructions }
        : {}),
      ...(courseMapUrlFromPayload !== undefined
        ? { courseMapUrl: courseMapUrlFromPayload }
        : {}),
      ...(courseSlugFromPayload !== undefined
        ? { courseSlug: courseSlugFromPayload }
        : {}),
      ...(startLineLabel !== undefined ? { startLineLabel } : {}),
      ...(finishLineLabel !== undefined ? { finishLineLabel } : {}),
      ...(isLoop !== undefined ? { isLoop } : {}),
      ...(resultsUrlFromPayload !== undefined
        ? { resultsUrl: resultsUrlFromPayload }
        : {}),
      ...(summaryPhrase !== undefined ? { summaryPhrase } : {}),
      ...(charityNameResolved !== undefined
        ? { charityName: charityNameResolved }
        : {}),
      ...(charityUrlExtra !== undefined ? { charityUrl: charityUrlExtra } : {}),
      ...(officialWebsiteUrl !== undefined
        ? { officialWebsiteUrl }
        : {}),
      ...(registrationOpenNow !== undefined
        ? { registrationOpenNow }
        : {}),
      ...(registrationOpenDate !== undefined
        ? { registrationOpenDate }
        : {}),
      ...(registrationCloseDate !== undefined
        ? { registrationCloseDate }
        : {}),
      ...(registrationSoldOut !== undefined ? { registrationSoldOut } : {}),
      ...(transferDeadline !== undefined ? { transferDeadline } : {}),
      ...(registrationFee !== undefined ? { registrationFee } : {}),
      ...(companyRegistrationId !== null
        ? { companyRegistrationId }
        : {}),
      ...(parentRaceId !== undefined ? { parentRaceId } : {}),
      updatedAt: new Date(),
    };

    const slugFinal = slugVal || companyRaceId;

    let target:
      | Awaited<ReturnType<typeof prisma.race_registry.findUnique>>
      | null = null;

    /** prodRaceId/registryId → companyRegistrationId → slug → companyRaceId+slug */
    if (registryId) {
      target = await prisma.race_registry.findUnique({
        where: { id: registryId },
      });
    }
    if (!target && companyRegistrationId) {
      target = await prisma.race_registry.findUnique({
        where: { companyRegistrationId },
      });
    }
    if (!target && slugVal) {
      target = await prisma.race_registry.findUnique({
        where: { slug: slugVal },
      });
    }
    if (!target && companyRaceId && slugVal) {
      target = await prisma.race_registry.findFirst({
        where: { companyRaceId, slug: slugVal },
      });
    }
    /** Merge onto existing row for same name + date (avoids slug-change double-create). */
    if (!target && nameVal && raceDate) {
      target = await findRegistryByNameAndDate(prisma, nameVal, raceDate);
    }

    let registryIdOut: string;

    if (target) {
      registryIdOut = target.id;
      await prisma.race_registry.update({
        where: { id: target.id },
        data: {
          ...updateData,
          slug: slugVal ?? target.slug ?? slugFinal,
        },
      });
    } else {
      if (!slugVal) {
        return {
          ok: false,
          status: 400,
          error: "slug is required to create a new race_registry row",
        };
      }
      const newId = registryId ?? randomUUID();
      const collision = await prisma.race_registry.findUnique({
        where: { id: newId },
      });
      if (collision) {
        registryIdOut = newId;
        await prisma.race_registry.update({
          where: { id: newId },
          data: {
            ...updateData,
            slug: slugVal ?? collision.slug ?? slugFinal,
          },
        });
      } else {
        registryIdOut = newId;
        await prisma.race_registry.create({
          data: {
            id: newId,
            country: "USA",
            isCancelled: false,
            ...updateData,
            slug: slugVal,
          },
        });
      }
    }

    const syncedSegmentCount = await syncRegistryCourseSegments(
      registryIdOut,
      racePayload
    );

    let segmentRowCount =
      syncedSegmentCount >= 0
        ? syncedSegmentCount
        : await prisma.race_registry_course_segments.count({
            where: { raceRegistryId: registryIdOut },
          });

    if (segmentRowCount === 0) {
      const courseSlug =
        readOptionalTrimmedString(racePayload, "courseSlug") ?? slugVal;
      const hydrated = await hydrateRegistryCourseSegmentsFromRaceManage({
        raceRegistryId: registryIdOut,
        courseSlug,
        raceSlug: slugVal,
      });
      if (hydrated.count > 0) {
        segmentRowCount = hydrated.count;
      }
    }

    const payloadSegmentCount = countWritableSegmentsInPayload(racePayload);
    if (payloadSegmentCount > 0 && segmentRowCount === 0) {
      return {
        ok: false,
        status: 502,
        error:
          "Push included course segments but none were written to prod registry (check segment shape or GOFAST_RACE_MANAGE_URL)",
      };
    }

    await prisma.athlete_races.updateMany({
      where: { raceRegistryId: registryIdOut },
      data: {
        name: nameVal,
        raceDate,
        ...(distanceMeters !== undefined ? { distanceMeters } : {}),
        ...(distanceLabel !== undefined ? { distanceLabel } : {}),
        city: locationCity,
        state,
        ...(slugVal ? { slug: slugVal } : {}),
        updatedAt: new Date(),
      },
    });

    const { syncRaceTriggerForRegistry } = await import("@/lib/race-triggers-sync");
    await syncRaceTriggerForRegistry(registryIdOut);

    const linkedPlans = await prisma.training_plans.findMany({
      where: { raceId: registryIdOut },
      select: { id: true, name: true },
    });
    for (const plan of linkedPlans) {
      const repaired = syncAutoGeneratedPlanNameForTerminal(plan.name, nameVal);
      if (repaired) {
        await prisma.training_plans.update({
          where: { id: plan.id },
          data: { name: repaired, updatedAt: new Date() },
        });
      }
    }

    const mirrorRow = await prisma.race_registry.findUnique({
      where: { id: registryIdOut },
      select: registryMirrorSelect,
    });
    if (!mirrorRow) {
      return { ok: false, status: 500, error: "Registry row missing after upsert" };
    }

    return {
      ok: true,
      race: {
        id: mirrorRow.id,
        name: mirrorRow.name,
        slug: mirrorRow.slug,
        raceDate: mirrorRow.raceDate,
        companyRaceId: mirrorRow.companyRaceId,
      },
      registryMirror: serializeRegistryMirror(mirrorRow),
    };
  } catch (error: unknown) {
    const err = error as { message?: string };
    console.error("[upsertRaceRegistryFromPayload]", error);
    return {
      ok: false,
      status: 500,
      error: err?.message || "Failed to update race registry",
    };
  }
}
